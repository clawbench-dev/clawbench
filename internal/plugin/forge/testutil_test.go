// 夹具本体在 internal/handlertest（各功能插件共用）。这里保留同名薄包装，
// 是为了让测试函数体不必改写——它们从 handler 包搬过来时就是这个形状。
type testEnv = handlertest.Env

func setupTestEnv(t *testing.T) (*testEnv, func()) {
	t.Helper()
	env, teardown := handlertest.Setup(t)
	// forge 的绑定与事件表；都在接口的读写路径上。
	for _, ddl := range []string{
		service.ProjectForgesDDL,
		service.ForgeItemsDDL,
		service.ForgeSyncStateDDL,
		service.ForgeEventDDL,
		service.ForgePipelineRunsDDL,
	} {
		_, err := store.WriteExec(ddl)
		require.NoError(t, err)
	}
	return env, teardown
}

func newRequest(t *testing.T, method, path string, body any) *http.Request {
	return handlertest.NewRequest(t, method, path, body)
}

func callHandler(handler http.HandlerFunc, req *http.Request) *httptest.ResponseRecorder {
	return handlertest.Call(handler, req)
}

func assertStatus(t *testing.T, w *httptest.ResponseRecorder, expected int) {
	handlertest.AssertStatus(t, w, expected)
}

func withProjectCookie(req *http.Request, projectPath string) *http.Request {
	return handlertest.WithProjectCookie(req, projectPath)
}

func createTestFile(t *testing.T, projectDir, relPath, content string) {
	handlertest.CreateFile(t, projectDir, relPath, content)
}

// setupPersistTestEnv points DataDir/BinDir at a temp directory so config.yaml
// writes land there instead of the real install.
func setupPersistTestEnv(t *testing.T) (*testEnv, func()) {
	t.Helper()
	env, teardown := setupTestEnv(t)

	origBinDir := model.BinDir
	origDataDir := model.DataDir
	tmpDir := t.TempDir()
	model.BinDir = tmpDir
	model.DataDir = tmpDir
	require.NoError(t, os.MkdirAll(filepath.Join(tmpDir, "config"), 0o755))

	origConfig := model.ConfigInstance
	origAutoGenerated := model.PasswordIsAutoGenerated

	cleanup := func() {
		model.BinDir = origBinDir
		model.DataDir = origDataDir
		model.ConfigInstance = origConfig
		model.PasswordIsAutoGenerated = origAutoGenerated
		teardown()
	}
	return env, cleanup
}

// withAuthCookie adds the clawbench_session cookie to the request.
func withAuthCookie(req *http.Request, token string) *http.Request {
	req.AddCookie(&http.Cookie{
		Name:  model.ScopedCookieName(model.SessionCookie),
		Value: token,
	})
	return req
}

// writeFile creates a file (and its parents) in the fixture tree.
func writeFile(t *testing.T, path, body string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

// newRepoFixture builds a realistic tree:
//
//	<root>/go.mod                                  module example.com/proj
//	<root>/internal/ai/backends/all/               (cwd of the generator)
//	<root>/internal/ai/backends/claude/agent.go
//	<root>/internal/ai/backends/codex/codex.go
//	<root>/internal/ai/backends/notes/README.md    (no Go: must be skipped)
//	<root>/internal/ai/backends/empty/             (empty: must be skipped)
//	<root>/internal/ai/backends/claude/data/       (nested dir: not a backend)
func newRepoFixture(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	writeFile(t, filepath.Join(root, "go.mod"), "module example.com/proj\n\ngo 1.22\n")
	for _, dir := range []string{"all", "claude", "codex", "notes", "empty", filepath.Join("claude", "data")} {
		if err := os.MkdirAll(filepath.Join(root, "internal", "ai", "backends", dir), 0o755); err != nil {
			t.Fatal(err)
		}
	}
	writeFile(t, filepath.Join(root, "internal", "ai", "backends", "claude", "agent.go"), "package claude\n")
	writeFile(t, filepath.Join(root, "internal", "ai", "backends", "codex", "codex.go"), "package codex\n")
	writeFile(t, filepath.Join(root, "internal", "ai", "backends", "notes", "README.md"), "not go\n")
	writeFile(t, filepath.Join(root, "internal", "ai", "backends", "claude", "data", "x.go"), "package data\n")
	return filepath.Join(root, "internal", "ai", "backends", "all")
}

// TestGenerate_WritesSortedBlankImports runs the generator the way go generate
// does: from the package directory, writing ./all.go. Only directories that
// really hold backend code may become blank imports — importing this package,
// a docs-only directory or a nested data folder would either fail the build or
// register nothing.
func TestGenerate_WritesSortedBlankImports(t *testing.T) {
	allDir := newRepoFixture(t)
	t.Chdir(allDir)

	names, err := generate("..")
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	if strings.Join(names, ",") != "claude,codex" {
		t.Fatalf("backends = %v, want [claude codex]", names)
	}

	out, err := os.ReadFile(targetFile)
	if err != nil {
		t.Fatalf("target not written: %v", err)
	}
	src := string(out)

	for _, line := range []string{
		"\t_ \"example.com/proj/internal/ai/backends/claude\"\n",
		"\t_ \"example.com/proj/internal/ai/backends/codex\"\n",
	} {
		if !strings.Contains(src, line) {
			t.Errorf("generated file is missing %q:\n%s", line, src)
		}
	}
	if strings.Contains(src, "_ \"example.com/proj/internal/ai/backends/all\"") {
		t.Errorf("the generator must not import its own package:\n%s", src)
	}
	if strings.Contains(src, "backends/notes") || strings.Contains(src, "backends/data") {
		t.Errorf("non-backend directories must be skipped:\n%s", src)
	}

	// Sorted, so regeneration is deterministic regardless of readdir order.
	claude := strings.Index(src, `"example.com/proj/internal/ai/backends/claude"`)
	codex := strings.Index(src, `"example.com/proj/internal/ai/backends/codex"`)
	if claude < 0 || codex < 0 || claude > codex {
		t.Errorf("imports must be sorted:\n%s", src)
	}

	// Header + package clause: the output must be gofmt-clean and buildable,
	// which is what format.Source guarantees (a misformatted body would break
	// the whole build instead of one code generator).
	if !strings.HasPrefix(src, "// Code generated by genbackendimports; DO NOT EDIT.\n") {
		t.Errorf("missing generated header:\n%s", src)
	}
	if !strings.Contains(src, "package all\n") {
		t.Errorf("missing package clause:\n%s", src)
	}

	// Idempotent: the generated file is itself Go source, but it lands in
	// `all`, which is excluded.
	if _, err := generate(".."); err != nil {
		t.Fatalf("second generate: %v", err)
	}
	again, err := os.ReadFile(targetFile)
	if err != nil {
		t.Fatal(err)
	}
	if string(again) != src {
		t.Error("regeneration must be byte-identical")
	}
}

func TestCollectBackends_ErrorsAreReported(t *testing.T) {
	// No backends at all means the generator was pointed at the wrong place;
	// writing an empty import block would silently unregister every backend.
	empty := t.TempDir()
	if _, err := collectBackends(empty); err == nil {
		t.Fatal("expected an error for a directory with no backend sub-packages")
	}

	// A missing directory is reported rather than read as "no backends".
	if _, err := collectBackends(filepath.Join(empty, "missing")); err == nil {
		t.Fatal("expected an error for a missing directory")
	}

	// A sub-directory this process cannot read is an error, not "no Go files":
	// silently dropping a backend is exactly the failure this generator exists
	// to prevent. Root ignores permissions, so the check only runs unprivileged.
	if os.Geteuid() != 0 {
		root := t.TempDir()
		locked := filepath.Join(root, "locked")
		if err := os.MkdirAll(locked, 0o755); err != nil {
			t.Fatal(err)
		}
		writeFile(t, filepath.Join(locked, "x.go"), "package locked\n")
		if err := os.Chmod(locked, 0o000); err != nil {
			t.Fatal(err)
		}
		t.Cleanup(func() { _ = os.Chmod(locked, 0o755) })
		if _, err := collectBackends(root); err == nil {
			t.Fatal("expected an unreadable backend directory to be reported")
		}
	}
}

func TestReadModulePath_WalksUpAndReportsBrokenTrees(t *testing.T) {
	root := t.TempDir()
	deep := filepath.Join(root, "a", "b", "c")
	if err := os.MkdirAll(deep, 0o755); err != nil {
		t.Fatal(err)
	}

	// No go.mod above the temp root: the walk must stop at the filesystem root
	// instead of looping, and say what it looked for.
	if _, err := readModulePath(deep); err == nil || !strings.Contains(err.Error(), "go.mod not found") {
		t.Fatalf("expected a 'go.mod not found' error, got %v", err)
	}

	// A go.mod without a module line is a broken repository, not an empty module
	// path (which would generate imports like "/internal/ai/backends/x").
	writeFile(t, filepath.Join(root, "go.mod"), "go 1.22\n")
	if _, err := readModulePath(deep); err == nil || !strings.Contains(err.Error(), "no module line") {
		t.Fatalf("expected a 'no module line' error, got %v", err)
	}

	// A valid one several levels up is found.
	writeFile(t, filepath.Join(root, "go.mod"), "module example.com/nested\n")
	got, err := readModulePath(deep)
	if err != nil {
		t.Fatalf("readModulePath: %v", err)
	}
	if got != "example.com/nested" {
		t.Fatalf("module = %q", got)
	}
}

// TestRepoGenerationMatchesCommittedFile is the guard that matters in CI: the
// committed all.go must be exactly what the generator produces today. A backend
// directory added without regenerating leaves that backend out of the binary (its
// init() never runs), and nothing else would notice.
func TestRepoGenerationMatchesCommittedFile(t *testing.T) {
	repoRoot := filepath.Join("..", "..", "..")
	allDir := filepath.Join(repoRoot, "internal", "ai", "backends", "all")
	committed, err := os.ReadFile(filepath.Join(allDir, targetFile))
	if err != nil {
		t.Fatalf("committed all.go not readable: %v", err)
	}

	generated, _, err := render(filepath.Join(allDir, ".."))
	if err != nil {
		t.Fatalf("render: %v", err)
	}
	if !bytes.Equal(committed, generated) {
		t.Fatalf("internal/ai/backends/all/all.go is stale; run go generate ./internal/ai/backends/all\n"+
			"--- committed ---\n%s\n--- generated ---\n%s", committed, generated)
	}
}

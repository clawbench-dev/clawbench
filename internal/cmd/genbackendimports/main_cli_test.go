package main

import (
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"

	"github.com/stretchr/testify/require"
)

// The generator is run through `go generate` (see backends/all/generate.go) and
// by hand. `main` adds no behavior beyond render + write + two log lines, so the
// only part worth pinning is that the log names the file and the backend count,
// and that a failure goes to stderr and exits non-zero. Both are observable only
// from a child process, hence the re-exec.
//
// The re-exec is the same pattern the package already uses for the repository
// check: the test binary runs itself with GENBACKENDIMPORTS_AS_MAIN=1, which makes
// TestMain call main() instead of the test runner.
func TestMain(m *testing.M) {
	if os.Getenv("GENBACKENDIMPORTS_AS_MAIN") == "1" {
		main()
		return
	}
	os.Exit(m.Run())
}

// runGeneratorAsChild runs this binary as the generator inside dir and returns its
// combined output and exit code.
func runGeneratorAsChild(t *testing.T, dir string) (string, int) {
	t.Helper()
	cmd := exec.Command(os.Args[0], "-test.run=^$")
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GENBACKENDIMPORTS_AS_MAIN=1")
	out, err := cmd.CombinedOutput()
	if err == nil {
		return string(out), 0
	}
	var exitErr *exec.ExitError
	require.ErrorAs(t, err, &exitErr, "output: %s", out)
	return string(out), exitErr.ExitCode()
}

// The success path prints one line naming the written file and how many backends
// it imported — the only feedback the maintainer gets from `go generate`.
func TestMain_WritesAndReportsTheBackendCount(t *testing.T) {
	allDir := newRepoFixture(t)

	out, code := runGeneratorAsChild(t, allDir)
	require.Zero(t, code, out)
	require.Contains(t, out, "genbackendimports: wrote all.go (2 backends)")
	require.FileExists(t, filepath.Join(allDir, targetFile))
}

// A directory with no backends is a wrong invocation (the user ran it from the
// repo root instead of the package). It must exit 1 with a message on stderr
// rather than writing an empty import block that silently unregisters every
// backend.
func TestMain_FailsLoudlyWhenThereAreNoBackends(t *testing.T) {
	dir := t.TempDir()
	// A nested `all` directory with a go.mod above it but no internal/ai/backends
	// sibling: the module walk succeeds and the backend scan is what fails.
	writeFile(t, filepath.Join(dir, "go.mod"), "module example.com/empty\n")
	allDir := filepath.Join(dir, "internal", "ai", "backends", "all")
	require.NoError(t, os.MkdirAll(allDir, 0o755))

	out, code := runGeneratorAsChild(t, allDir)
	require.Equal(t, 1, code, out)
	require.Contains(t, out, "genbackendimports:")
	require.Contains(t, out, "no backend sub-packages found")
	_, statErr := os.Stat(filepath.Join(allDir, targetFile))
	require.True(t, os.IsNotExist(statErr), "a failed run must not write a stale/empty file")
}

// A missing go.mod is reported by the same channel: exit 1 with the reason, not
// a panic trace (a maintainer running it in the wrong tree needs the message).
func TestMain_ReportsAMissingGoMod(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "internal", "ai", "backends", "claude", "x.go"), "package claude\n")

	out, code := runGeneratorAsChild(t, dir)
	require.Equal(t, 1, code, out)
	require.Contains(t, out, "go.mod not found")
}

// A directory that is not writable is the one write-path failure a generator can
// hit without a broken repo: the target cannot be created and the message has to
// say so instead of leaving a half-written file behind.
func TestGenerate_ReportsAnUnwritableTarget(t *testing.T) {
	allDir := newRepoFixture(t)
	// A directory where the file should go: WriteFile fails on every platform
	// (unlike a chmod, which Windows ignores).
	require.NoError(t, os.MkdirAll(filepath.Join(allDir, targetFile), 0o755))
	t.Chdir(allDir)

	names, err := generate()
	require.Error(t, err, "writing over a directory must fail")
	require.Nil(t, names)
}

// The rendered source must be valid Go on its own: a backend name with a quote in
// it would otherwise produce a file that fails to compile, and format.Source is
// what turns that into an error here instead of in the build.
func TestRender_ProducesCompilableSource(t *testing.T) {
	// This test runs with its package directory as the working directory.
	backendsDir := filepath.Join("..", "..", "ai", "backends")
	src, names, err := render(backendsDir)
	require.NoError(t, err)
	require.NotEmpty(t, names)
	require.NotEmpty(t, src)

	text := string(src)
	require.True(t, strings.HasPrefix(text, "// Code generated by genbackendimports; DO NOT EDIT.\n"))
	require.Contains(t, text, "package all\n")
	for _, name := range names {
		require.Contains(t, text, "_ \"clawbench/internal/ai/backends/"+name+"\"")
	}
	// Self-import would be an import cycle, and the generator excludes itself.
	require.NotContains(t, text, "backends/all\"")
}

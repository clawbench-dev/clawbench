// Command genbackendimports regenerates internal/ai/backends/all/all.go.
//
// Go has no runtime package discovery: a backend's init() only runs if
// something imports its package. Rather than hand-maintaining twenty blank
// imports (in main.go plus every test that needs the real backend set), the
// list is generated from the directory layout — adding a backend directory is
// the only step.
//
// Run it via:
//
//	go generate ./internal/ai/backends/all
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const (
	backendsDir = ".."       // cwd is internal/ai/backends/all
	selfPkg     = "all"      // never import ourselves
	targetFile  = "all.go"   // relative to cwd
	dirPrefix   = "backends" // last path element before the backend name
)

func main() {
	names, err := generate()
	if err != nil {
		fail(err)
	}
	fmt.Printf("genbackendimports: wrote %s (%d backends)\n", targetFile, len(names))
}

// generate renders the package source and writes it to targetFile in the
// current directory (which is internal/ai/backends/all when run via go
// generate). It returns the import list it wrote, for the log line.
func generate() ([]string, error) {
	src, names, err := render(backendsDir)
	if err != nil {
		return nil, err
	}
	if err := os.WriteFile(targetFile, src, 0o644); err != nil {
		return nil, err
	}
	return names, nil
}

// render generates the package source for the backends found under backendsDir.
//
// It is split out of main so the generator can be tested against a temporary
// directory tree; main only decides where to write the result.
func render(backendsDir string) ([]byte, []string, error) {
	module, err := readModulePath(backendsDir)
	if err != nil {
		return nil, nil, err
	}
	names, err := collectBackends(backendsDir)
	if err != nil {
		return nil, nil, err
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by genbackendimports; DO NOT EDIT.\n")
	b.WriteString("//\n")
	b.WriteString("// Regenerate with: go generate ./internal/ai/backends/all\n")
	b.WriteString("//\n")
	b.WriteString("// Every backend sub-package registers itself in init(). Importing this\n")
	b.WriteString("// package for side effects is how the application gets the full backend set;\n")
	b.WriteString("// adding a backend directory is the only step needed to extend it.\n")
	b.WriteString("package all\n\n")
	b.WriteString("import (\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\t_ %q\n", module+"/internal/ai/"+dirPrefix+"/"+n)
	}
	b.WriteString(")\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, nil, fmt.Errorf("gofmt generated source: %w", err)
	}
	return src, names, nil
}

// collectBackends returns the sub-directory names of the backends package that
// contain Go source, excluding this generator's own package.
func collectBackends(backendsDir string) ([]string, error) {
	entries, err := os.ReadDir(backendsDir)
	if err != nil {
		return nil, err
	}
	var names []string
	for _, e := range entries {
		if !e.IsDir() || e.Name() == selfPkg {
			continue
		}
		hasGo, err := dirHasGoFile(filepath.Join(backendsDir, e.Name()))
		if err != nil {
			return nil, err
		}
		if hasGo {
			names = append(names, e.Name())
		}
	}
	sort.Strings(names)
	if len(names) == 0 {
		return nil, fmt.Errorf("no backend sub-packages found under %s", backendsDir)
	}
	return names, nil
}

func dirHasGoFile(dir string) (bool, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return false, err
	}
	for _, e := range entries {
		if !e.IsDir() && strings.HasSuffix(e.Name(), ".go") {
			return true, nil
		}
	}
	return false, nil
}

// readModulePath finds the enclosing go.mod above startDir and returns its
// module path.
func readModulePath(startDir string) (string, error) {
	dir, err := filepath.Abs(startDir)
	if err != nil {
		return "", err
	}
	for {
		data, err := os.ReadFile(filepath.Join(dir, "go.mod"))
		if err == nil {
			for _, line := range strings.Split(string(data), "\n") {
				if strings.HasPrefix(line, "module ") {
					return strings.TrimSpace(strings.TrimPrefix(line, "module ")), nil
				}
			}
			return "", fmt.Errorf("%s has no module line", filepath.Join(dir, "go.mod"))
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("go.mod not found above %s", dir)
		}
		dir = parent
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "genbackendimports:", err)
	os.Exit(1)
}

// ParsePresenceMap walks a raw YAML map and returns a flat set of dot-separated
// keys that were explicitly present. For example, given:
//
//	port_forward:
//	  enabled: true
//
// It returns: {"port_forward": true, "port_forward.enabled": true}
func ParsePresenceMap(raw map[string]any) map[string]bool {
	presence := make(map[string]bool)
	walkPresenceMap(raw, "", presence)
	return presence
}

func walkPresenceMap(m map[string]any, prefix string, presence map[string]bool) {
	for key, val := range m {
		fullKey := key
		if prefix != "" {
			fullKey = prefix + "." + key
		}
		presence[fullKey] = true
		if nested, ok := val.(map[string]any); ok {
			walkPresenceMap(nested, fullKey, presence)
		}
	}
}

// ApplyDefaults fills zero-value fields in cfg with sensible defaults.
// presence indicates which keys were explicitly set in the config file,
// used to distinguish "user wrote enabled: false" from "user omitted the section".
// Returns the auto-generated password if one was created, empty string otherwise.
func ApplyDefaults(cfg *Config, presence map[string]bool) string { //nolint:gocognit,gocyclo // exhaustive default application for all config fields
	var autoPassword string

	// --- Server ---
	if cfg.Port <= 0 {
		cfg.Port = 20000
	}

	// --- Language ---
	// UI language for background-localized strings (scheduled tasks, pushes,
	// auto-continue). "zh" matches the frontend's fallbackLocale, so a server
	// that has never been told the user's language behaves like the UI does.
	// An explicit value from config.yaml wins; the frontend overwrites it on
	// the first locale change.
	if cfg.Language == "" {
		cfg.Language = DefaultLanguage
	}

	// --- TLS ---
	// Migrate legacy enabled/cert_file/key_file fields to the new cert_dir scheme.
	// If cert_dir is unset but legacy cert_file points to an existing directory
	// containing the cert, derive cert_dir from it (the cert directory already
	// holds the matching key file per the standard layouts).
	if cfg.TLS.CertDir == "" && cfg.TLS.CertFile != "" {
		if dir := filepath.Dir(cfg.TLS.CertFile); dir != "." {
			cfg.TLS.CertDir = dir
		}
	}
	// Default cert directory when neither new nor legacy TLS is configured.
	if cfg.TLS.CertDir == "" {
		cfg.TLS.CertDir = DefaultTLSCertDir()
	}

	// --- Fonts ---
	// Custom font directory defaults to <DataDir>/fonts when unset.
	if cfg.Fonts.Dir == "" {
		cfg.Fonts.Dir = DefaultFontsDir()
	}

	// --- DevPort ---
	// -1 = explicitly disabled; 0 = auto (Port+2 when TLS active, disabled otherwise)
	if cfg.DevPort == 0 {
		if cfg.ResolveTLSActive() {
			cfg.DevPort = cfg.Port + 2
		}
	}

	// --- LogLevel ---
	if cfg.LogLevel == "" {
		cfg.LogLevel = "info"
	}

	// --- Password ---
	autoPasswordFile := filepath.Join(DataDir, "auto-password")
	if cfg.Password == "" {
		// Try to reuse previously auto-generated password
		saved, err := os.ReadFile(autoPasswordFile)
		if err == nil && len(saved) > 0 {
			cfg.Password = string(saved)
		} else {
			// Generate new random password (32 hex chars = 16 bytes = 128 bits entropy)
			// ISS-269: increased from 4 bytes (32-bit) to 16 bytes (128-bit)
			// to make offline brute-force infeasible
			b := make([]byte, 16)
			if _, err := rand.Read(b); err != nil {
				// Random generation failure is fatal — password would be predictable
				fmt.Fprintf(os.Stderr, "FATAL: crypto/rand.Read failed: %v\n", err)
				os.Exit(1)
			}
			cfg.Password = fmt.Sprintf("%x", b)
			// Persist for reuse across restarts
			_ = os.MkdirAll(filepath.Dir(autoPasswordFile), 0o755)
			_ = os.WriteFile(autoPasswordFile, []byte(cfg.Password), 0o600)
		}
		autoPassword = cfg.Password
		PasswordIsAutoGenerated = true
	} else {
		// cfg.Password came from config.yaml. Decide whether it is a leaked auto
		// password (written by a build that dumped the whole ConfigInstance on a
		// fresh install) or a genuine user choice. A user-set password is stored
		// as sha256:<hex>, so only a leaked one can byte-for-byte equal the
		// plaintext auto-password file.
		saved, readErr := os.ReadFile(autoPasswordFile)
		switch {
		case readErr == nil && len(saved) > 0 && strings.TrimSpace(string(saved)) == cfg.Password:
			// Leaked auto password. Keep the file — it is still the live
			// password — and mark it so it is stripped from config.yaml on the
			// next write, letting the install return to "no password configured".
			PasswordIsAutoGenerated = true
			autoPassword = cfg.Password
		case readErr != nil && !os.IsNotExist(readErr):
			// The file exists but could not be read, so the match above could not
			// run. Removing it would destroy the live password if the file is in
			// fact the real one, and forcing the marker true would strip a
			// genuine user password from config.yaml (locking the user out).
			// Leave both untouched — the conservative choice.
			slog.Warn("auto-password file is unreadable; leaving it and the marker untouched",
				"file", autoPasswordFile, "err", readErr)
		default:
			// No file, or it does not match: a genuine user password.
			_ = os.Remove(autoPasswordFile)
			PasswordIsAutoGenerated = false
		}
	}

	// --- LogDir ---
	// LogDir is always <DataDir>/logs — not configurable via config.yaml.
	// This avoids relative-path pitfalls (CWD-dependent resolution).
	cfg.LogDir = filepath.Join(DataDir, "logs")

	if cfg.LogMaxDays <= 0 {
		cfg.LogMaxDays = 7
	}

	// --- Upload ---
	if cfg.Upload.MaxSizeMB <= 0 {
		cfg.Upload.MaxSizeMB = 100
	}
	if cfg.Upload.MaxFiles <= 0 {
		cfg.Upload.MaxFiles = 20
	}
	// Upload retention defaults to OFF: deleting a user's files is destructive
	// and irreversible, so it must be an explicit opt-in rather than something
	// a fresh install does on its own.
	//
	// The day count defaults to 30 even while disabled, so turning the switch on
	// has an effect immediately. Leaving it at 0 would make "enabled + 0 days"
	// mean "keep forever" — the user flips the switch, the UI says cleanup is
	// on, and the worker silently no-ops.
	if cfg.Upload.RetentionDays <= 0 {
		cfg.Upload.RetentionDays = 30
	}

	// --- Chat ---
	if cfg.Chat.InitialMessages <= 0 {
		cfg.Chat.InitialMessages = 20
	}
	if cfg.Chat.PageSize <= 0 {
		cfg.Chat.PageSize = 20
	}
	if cfg.Chat.SessionPageSize <= 0 {
		cfg.Chat.SessionPageSize = 10
	}
	// SystemPromptInterval: 0 = never re-inject is the intentional DEFAULT.
	// The old `<= 0 → 10` rewrite made 0 unexpressable — a user who
	// explicitly disabled periodic re-injection was silently switched back
	// to every-10-turns. Negative values (hand-edited yaml only; PATCH
	// rejects them earlier) clamp to 0.
	// 0 = 从不重注即为默认值。旧的 `<= 0 → 10` 改写使 0 无法表达——显式
	// 关闭周期性重注的用户会被静默改回每 10 轮。负值(仅手改 yaml 可产生;
	// PATCH 已在更早处拦截)收敛为 0。
	if cfg.Chat.SystemPromptInterval < 0 {
		cfg.Chat.SystemPromptInterval = 0
	}
	// RecommendEnabled: bool zero-value (false) is the intentional default.
	// Use presence map to distinguish "user wrote false" from "user omitted the field".
	if p, ok := presence["chat.recommend_enabled"]; !ok || !p {
		cfg.Chat.RecommendEnabled = false
	}
	if cfg.Chat.RecommendContextMessages <= 0 {
		cfg.Chat.RecommendContextMessages = 10
	}
	// ForkContextBudget bounds the history text re-injected when forking or
	// rewinding a session. 0/negative (omitted field, or hand-edited yaml)
	// falls back to the default rather than meaning "inject nothing".
	if cfg.Chat.ForkContextBudget <= 0 {
		cfg.Chat.ForkContextBudget = DefaultForkContextBudget
	}
	// AutoContinueEnabled: bool zero-value (false) is the intentional default —
	// auto-resuming a session spends tokens without the user asking, so it is
	// opt-in. Use the presence map to distinguish "user wrote false" from
	// "user omitted the field".
	if p, ok := presence["chat.auto_continue_enabled"]; !ok || !p {
		cfg.Chat.AutoContinueEnabled = false
	}
	// AutoContinueMaxRetries: -1 (unlimited) and 0 (retries disabled) are both
	// meaningful, so this CANNOT use a `<= 0 → default` rewrite — that would
	// silently turn "unlimited" into 3. Only an omitted field takes the default.
	if p, ok := presence["chat.auto_continue_max_retries"]; !ok || !p {
		cfg.Chat.AutoContinueMaxRetries = DefaultAutoContinueMaxRetries
	}
	// RestartResumeWindowMinutes: 0 is MEANINGFUL ("no age bound"), so this cannot
	// use a `<= 0 → default` rewrite — that would silently turn "resume
	// regardless of age" into an hour. Only an omitted field takes the default.
	if p, ok := presence["chat.restart_resume_window_minutes"]; !ok || !p {
		cfg.Chat.RestartResumeWindowMinutes = DefaultRestartResumeWindowMinutes
	}
	// Negative values other than the -1 sentinel are unrepresentable (PATCH
	// rejects them too); clamp to 0 so a hand-edited yaml cannot produce a
	// value that would be read as "unlimited" by accident.
	if cfg.Chat.AutoContinueMaxRetries < AutoContinueUnlimited {
		cfg.Chat.AutoContinueMaxRetries = 0
	}
	// AutoRenameEnabled: default ON. This costs nothing on an install that has
	// not configured the shared ai_summary model: the AI layer is gated a
	// second time on that model being present (service.AutoRenameEnabled), so
	// the session simply keeps its synchronous local title — the fallback is
	// the pre-existing behavior, not a new failure mode. Use the presence map
	// to distinguish "user wrote false" (opt-out, kept) from "user omitted the
	// field" (takes the default).
	if !presence["chat.auto_rename_enabled"] {
		cfg.Chat.AutoRenameEnabled = true
	}
	// --- User identity ---
	// The nickname is NOT defaulted to "User" here. The literal is a fallback
	// applied where the name is actually used (group routing's
	// groupUserTarget(), the settings/meeting UI), so an empty stored value
	// means "the user never configured one" — which is distinguishable from a
	// user who explicitly chose the word "User". Trimming covers a hand-edited
	// config.yaml; the mention parser trims each target, so an untrimmed
	// nickname would be unreachable.
	cfg.User.Nickname = strings.TrimSpace(cfg.User.Nickname)
	// The profile is injected into every agent system prompt, so a hand-edited
	// value is clamped rather than allowed to grow without bound. The PATCH
	// path rejects an over-long value with a 400 instead of silently trimming.
	cfg.User.Profile = strings.TrimSpace(cfg.User.Profile)
	if runes := []rune(cfg.User.Profile); len(runes) > MaxUserProfileRunes {
		cfg.User.Profile = string(runes[:MaxUserProfileRunes])
	}
	// GroupMaxSpeeches: the member-to-member speech cap for a group turn.
	// A non-positive value is nonsensical (it would stop the discussion before
	// anyone spoke), so it falls back to the default. The default is generous
	// enough that a normal discussion is stopped by the host's end signal or
	// by the members @-ing the human, not by this cap — it exists to bound a
	// runaway relay (A@B, B@A).
	if cfg.Chat.GroupMaxSpeeches <= 0 {
		cfg.Chat.GroupMaxSpeeches = 100
	}
	// RecentProjectCardsMaxCount: how many "other projects" cards the session
	// list may show. 0 is not meaningful here (it would hide the section
	// entirely, which is what an empty active set already does), so a
	// non-positive value falls back to the default rather than being kept.
	if cfg.Chat.RecentProjectCardsMaxCount <= 0 {
		cfg.Chat.RecentProjectCardsMaxCount = 10
	}
	// RecentProjectCardsWindowHours: how far back a project still earns a
	// collapsed card. A non-positive window would mean "no project is recent",
	// which is indistinguishable from turning the feature off — so it falls back
	// to the default rather than being kept.
	if cfg.Chat.RecentProjectCardsWindowHours <= 0 {
		cfg.Chat.RecentProjectCardsWindowHours = 24
	}
	// SessionSortRecent: bool zero-value (false) is the intentional default —
	// ordering never-dragged rows by activity reshuffles the sidebar while the
	// user reads it. Use the presence map to distinguish "user wrote false" from
	// "user omitted the field".
	if p, ok := presence["chat.session_sort_recent"]; !ok || !p {
		cfg.Chat.SessionSortRecent = false
	}

	// --- Session ---
	// MaxCount: 0 means "unlimited" (the create-session gate is `> 0`), so it is
	// an expressible value, not a zero-value to be defaulted. Only an omitted
	// key takes the default. Rewriting an explicit 0 to 15 made "unlimited"
	// unexpressable in config.yaml — an install that opted out of the limit was
	// silently enrolled in one. Negative values are nonsensical; clamp them to
	// the default rather than letting them reach the `> 0` gate (which would
	// read a negative as unlimited).
	if p, ok := presence["session.max_count"]; ok && p {
		if cfg.Session.MaxCount < 0 {
			cfg.Session.MaxCount = 15
		}
	} else if cfg.Session.MaxCount <= 0 {
		cfg.Session.MaxCount = 15
	}
	// ArchiveRetentionEnabled: bool zero-value (false) is intentional default.
	// Use presence map to distinguish "user wrote false" from "user omitted the field".
	if p, ok := presence["session.archive_retention_enabled"]; ok && p {
		// User explicitly set archive_retention_enabled, keep their value
	} else {
		cfg.Session.ArchiveRetentionEnabled = false
	}
	// ArchiveRetentionDays: 0 = keep forever is the intentional DEFAULT —
	// archived sessions should not vanish by surprise. The old `<= 0 → 30`
	// rewrite made 0 unexpressable, so a user who wanted retention disabled
	// was silently enrolled in a 30-day purge. Negative values clamp to 0.
	// 0 = 永久保留即为默认值——归档会话不应莫名消失。旧的 `<= 0 → 30` 改写
	// 使 0 无法表达,想关闭留存的用户被静默纳入 30 天清理。负值收敛为 0。
	if cfg.Session.ArchiveRetentionDays < 0 {
		cfg.Session.ArchiveRetentionDays = 0
	}

	// --- Recent Projects ---
	if cfg.RecentProjects.MaxCount <= 0 {
		cfg.RecentProjects.MaxCount = 10
	}

	// --- Port Forward ---
	// Enabled only says "the feature exists". Which wire carries the forwards
	// is decided by Transport below — that is what actually opens or skips the
	// SSH listener.
	//
	// It is pinned here (rather than left to the file) because there is no
	// longer a per-deployment reason to hide the whole feature: an install that
	// only exposes the main HTTP port simply runs transport: h2. The bool
	// zero-value trap no longer applies either, so a config that says false is
	// converged on load.
	cfg.PortForward.Enabled = true
	// Persist host key to avoid SSH fingerprint mismatch after server restart
	if cfg.PortForward.HostKey == "" {
		cfg.PortForward.HostKey = filepath.Join(DataDir, "ssh_host_key")
	}
	// Transport is the server-side switch the clients follow. An omitted value,
	// the retired "both" and anything unrecognized converge on the default
	// (h2); "ssh" is the only other effective value.
	//
	// This is the single repair point for hand-edited config.yaml: there is no
	// standalone validator on the load path, so garbage would otherwise survive
	// until the first PATCH.
	cfg.PortForward.Transport = NormalizePortForwardTransport(cfg.PortForward.Transport)

	// --- TTS ---
	if cfg.TTS.Engine == "" {
		cfg.TTS.Engine = "edge"
	}
	// Legacy agent-based summarize backends are gone: the agent CLIs are no
	// longer summarizer backends, and the LLM path is the shared ai_summary
	// model. Drop the value instead of migrating it — there is no equivalent to
	// map it onto (guessing "api" left upgraded installs pointing at a backend
	// with nothing bound, which read as a broken configuration forever).
	agentBackends := map[string]bool{
		"claude": true, "codebuddy": true, "opencode": true, "codex": true,
		"qoder": true, "vecli": true, "deepseek": true, "pi": true, "mimo": true,
	}
	if agentBackends[cfg.Summarize.TTSBackend] {
		slog.Warn("summarize.tts_backend is a removed agent backend, falling back to simple", slog.String("old", cfg.Summarize.TTSBackend))
		cfg.Summarize.TTSBackend = ""
	}
	if cfg.Summarize.TTSBackend == "" {
		cfg.Summarize.TTSBackend = "simple"
	}
	// AutoJunkRatio is the "auto" backend's routing threshold. Treat the zero
	// value as unset (a pre-existing config lacks the field) and default it to
	// 0.5; a threshold of 0 would route even fully-clean text to the LLM, which
	// is never useful — use tts_backend "api" for that instead.
	if cfg.Summarize.AutoJunkRatio <= 0 || cfg.Summarize.AutoJunkRatio > 1 {
		cfg.Summarize.AutoJunkRatio = 0.5
	}

	// --- Meeting (AI 听记 / minutes) ---
	// Three bool zero-value traps: all default ON, so only an explicit false in
	// config.yaml turns them off. The presence map is what distinguishes "the
	// user opted out" from "the field did not exist before this release".
	if !presence["meeting.auto_minutes"] {
		cfg.Meeting.AutoMinutes = true
	}
	if !presence["meeting.proofread"] {
		cfg.Meeting.Proofread = true
	}
	if !presence["meeting.file_excerpts"] {
		cfg.Meeting.FileExcerpts = true
	}
	if cfg.Meeting.MinutesMaxTokens < 0 {
		cfg.Meeting.MinutesMaxTokens = DefaultMeetingMinutesMaxTokens
	}
	// Clamp hand-edited values instead of failing startup: an out-of-range cap
	// is a bad preference, not a broken installation. 0 is the auto sentinel and
	// must survive this clamp — only a positive value is pushed into the manual
	// range.
	if cfg.Meeting.MinutesMaxTokens > 0 && cfg.Meeting.MinutesMaxTokens < MinMeetingMinutesMaxTokens {
		cfg.Meeting.MinutesMaxTokens = MinMeetingMinutesMaxTokens
	}
	if cfg.Meeting.MinutesMaxTokens > MaxMeetingMinutesMaxTokens {
		cfg.Meeting.MinutesMaxTokens = MaxMeetingMinutesMaxTokens
	}
	// Empty means "follow the transcript". An unknown value from a hand-edited
	// file falls back to the same default rather than producing a prompt in a
	// language the user did not choose.
	switch cfg.Meeting.Language {
	case "", "zh", "en":
	default:
		cfg.Meeting.Language = ""
	}

	// --- AISummary (shared AI model config) ---
	// Legacy TTS summary config (summarize.tts_model / summarize.tts_api) was
	// removed from the typed struct, so it no longer unmarshals and is simply
	// ignored. Here we only ensure a format default.
	if cfg.AISummary.API.BaseURL != "" && cfg.AISummary.Format == "" {
		cfg.AISummary.Format = "openai"
	}
	if cfg.TTS.Speed <= 0 {
		cfg.TTS.Speed = 1.0
	}
	if cfg.TTS.InlineCodeMaxLen <= 0 {
		cfg.TTS.InlineCodeMaxLen = 100
	}
	if cfg.TTS.MaxSummarizeRunes <= 0 {
		cfg.TTS.MaxSummarizeRunes = 10000
	}
	// MaxCacheFiles: -1 or 0 both mean unlimited; positive = cap
	// We treat 0 as the default (100) for UX convenience,
	// and -1 as explicitly unlimited.
	if cfg.TTS.MaxCacheFiles == 0 {
		cfg.TTS.MaxCacheFiles = 100
	}
	// OpenAI-compatible TTS: default the stream mode to "auto" (per-model
	// choice). An unknown value is left untouched so validation can reject it.
	if cfg.TTS.OpenAI.StreamMode == "" {
		cfg.TTS.OpenAI.StreamMode = "auto"
	}
	// Vendor engines: unlike the OpenAI-compatible engine (whose model and
	// voice space is unbounded and therefore left empty), these three publish
	// a fixed catalog, so a usable default keeps an engine switch from landing
	// on a blank form that fails at synthesis time.
	if cfg.TTS.Alibaba.BaseURL == "" {
		cfg.TTS.Alibaba.BaseURL = "https://dashscope.aliyuncs.com"
	}
	if cfg.TTS.Alibaba.Model == "" {
		cfg.TTS.Alibaba.Model = "cosyvoice-v3-flash"
	}
	if cfg.TTS.Alibaba.Voice == "" {
		cfg.TTS.Alibaba.Voice = "longanyang"
	}
	if cfg.TTS.Tencent.VoiceType <= 0 {
		cfg.TTS.Tencent.VoiceType = 101001
	}
	if cfg.TTS.Volcano.ResourceID == "" {
		cfg.TTS.Volcano.ResourceID = "seed-tts-2.0"
	}
	if cfg.TTS.Volcano.Voice == "" {
		cfg.TTS.Volcano.Voice = "zh_female_vv_uranus_bigtts"
	}
	if cfg.TTS.Minimax.BaseURL == "" {
		cfg.TTS.Minimax.BaseURL = "https://api.minimax.chat"
	}
	if cfg.TTS.Minimax.Model == "" {
		cfg.TTS.Minimax.Model = "speech-02-hd"
	}
	if cfg.TTS.Minimax.Voice == "" {
		cfg.TTS.Minimax.Voice = "female-shaonv"
	}

	// --- STT ---
	// Each engine's own defaults. They are applied unconditionally (not only for
	// the selected engine) so switching the engine in the settings UI starts
	// from a usable configuration instead of an empty endpoint.
	if cfg.STT.VLLM.BaseURL == "" {
		cfg.STT.VLLM.BaseURL = "http://localhost:8000/v1"
	}
	if cfg.STT.VLLM.Model == "" {
		cfg.STT.VLLM.Model = "openai/whisper-large-v3"
	}
	if cfg.STT.VLLM.Language == "" {
		cfg.STT.VLLM.Language = "zh"
	}
	if cfg.STT.VLLM.ChunkMs <= 0 {
		cfg.STT.VLLM.ChunkMs = 1000
	}
	if cfg.STT.Doubao.ResourceID == "" {
		cfg.STT.Doubao.ResourceID = "volc.seedasr.sauc.duration"
	}
	if cfg.STT.Alibaba.BaseURL == "" {
		cfg.STT.Alibaba.BaseURL = "https://dashscope.aliyuncs.com"
	}
	if cfg.STT.Alibaba.Model == "" {
		cfg.STT.Alibaba.Model = "paraformer-realtime-v2"
	}
	if cfg.STT.Alibaba.Language == "" {
		cfg.STT.Alibaba.Language = "zh"
	}
	if cfg.STT.Tencent.Model == "" {
		cfg.STT.Tencent.Model = "16k_zh"
	}
	// Bool zero-value trap: ITN and punctuation default to ON, so only an
	// explicit value in config.yaml may turn them off. The presence map uses the
	// per-engine paths — a shared path would let one engine's explicit false
	// silently switch the other engine's default off too.
	if _, ok := presence["stt.doubao.enable_itn"]; !ok {
		cfg.STT.Doubao.EnableITN = true
	}
	if _, ok := presence["stt.doubao.enable_punc"]; !ok {
		cfg.STT.Doubao.EnablePunc = true
	}
	if _, ok := presence["stt.alibaba.enable_itn"]; !ok {
		cfg.STT.Alibaba.EnableITN = true
	}
	if _, ok := presence["stt.alibaba.enable_punc"]; !ok {
		cfg.STT.Alibaba.EnablePunc = true
	}
	if _, ok := presence["stt.tencent.enable_itn"]; !ok {
		cfg.STT.Tencent.EnableITN = true
	}
	// Tencent streams by default: realtime has no 60-second ceiling and returns
	// text while the user is still speaking. Only an explicit false turns it
	// off, which switches dictation to a WAV upload.
	if _, ok := presence["stt.tencent.streaming"]; !ok {
		cfg.STT.Tencent.Streaming = true
	}
	if cfg.STT.Doubao.EndWindowSize <= 0 {
		cfg.STT.Doubao.EndWindowSize = 800
	}
	if cfg.STT.Alibaba.EndWindowSize <= 0 {
		cfg.STT.Alibaba.EndWindowSize = 800
	}
	if cfg.STT.Tencent.EndWindowSize <= 0 {
		cfg.STT.Tencent.EndWindowSize = 1000
	}
	if cfg.STT.ShortcutKey == "" {
		cfg.STT.ShortcutKey = "F9"
	}
	// Microphone preprocessing defaults to ON, so the zero value in an existing
	// config.yaml would otherwise silently turn every switch off. Only an
	// explicit `false` may disable one.
	if _, ok := presence["stt.mic_echo_cancel"]; !ok {
		cfg.STT.MicEchoCancel = true
	}
	if _, ok := presence["stt.mic_noise_suppress"]; !ok {
		cfg.STT.MicNoiseSuppress = true
	}
	if _, ok := presence["stt.mic_auto_gain"]; !ok {
		cfg.STT.MicAutoGain = true
	}
	if _, ok := presence["stt.mic_band_filter"]; !ok {
		cfg.STT.MicBandFilter = true
	}
	if _, ok := presence["stt.voice_gate"]; !ok {
		cfg.STT.VoiceGate = true
	}
	if cfg.STT.VoiceGateSensitivity == "" {
		cfg.STT.VoiceGateSensitivity = "standard"
	}
	// An EMPTY word list is a real choice ("no trigger words, use the pause"),
	// so the default applies on absence only — the same presence-map trap as the
	// bool switches above.
	if _, ok := presence["stt.trigger_words"]; !ok {
		cfg.STT.TriggerWords = "发送,好了,就这样"
	}
	// Zero is a legitimate value ("a pause never sends"), so the default has to
	// be applied on ABSENCE, not on the zero value — the same trap the bool
	// switches above have.
	if _, ok := presence["stt.silence_send_seconds"]; !ok {
		cfg.STT.SilenceSendSeconds = 3
	}
	// Same trap: 0 means "never leave", which is a real choice.
	if _, ok := presence["stt.idle_exit_seconds"]; !ok {
		cfg.STT.IdleExitSeconds = 60
	}
	if cfg.STT.BargeIn == "" {
		cfg.STT.BargeIn = "any"
	}
	if _, ok := presence["stt.barge_in_words"]; !ok {
		cfg.STT.BargeInWords = "等等,停一下"
	}

	// --- RAG ---
	// Bool zero-value trap: default to true when absent from config.
	if !presence["rag.vector_enabled"] {
		cfg.RAG.VectorEnabled = true
	}
	// FTS is always enabled. The Enabled field controls vector embedding only.
	// Backward compatibility: migrate deprecated Ollama fields to new generic fields.
	if cfg.RAG.BaseURL == "" && cfg.RAG.OllamaBaseURL != "" {
		cfg.RAG.BaseURL = cfg.RAG.OllamaBaseURL
	}
	if cfg.RAG.Model == "" && cfg.RAG.OllamaModel != "" {
		cfg.RAG.Model = cfg.RAG.OllamaModel
	}
	if cfg.RAG.BaseURL == "" {
		cfg.RAG.BaseURL = "http://localhost:11434"
	}
	if cfg.RAG.Model == "" {
		cfg.RAG.Model = "bge-m3"
	}
	if cfg.RAG.ChunkSize <= 0 {
		cfg.RAG.ChunkSize = 512
	}
	if cfg.RAG.ChunkOverlap <= 0 {
		cfg.RAG.ChunkOverlap = 64
	}
	if cfg.RAG.PollInterval == "" {
		cfg.RAG.PollInterval = "5s"
	}
	if cfg.RAG.BatchSize <= 0 {
		cfg.RAG.BatchSize = 50
	}
	if cfg.RAG.SearchLimit <= 0 {
		cfg.RAG.SearchLimit = 100
	}
	if cfg.RAG.SearchPoolSize <= 0 {
		cfg.RAG.SearchPoolSize = 20
	}
	if cfg.RAG.RetentionDays <= 0 {
		cfg.RAG.RetentionDays = 90
	}

	// --- Terminal ---
	// Bool zero-value trap: same as proxy/port_forward — default to true when absent.
	if !presence["terminal.enabled"] {
		cfg.Terminal.Enabled = true
	}
	if cfg.Terminal.IdleTimeout == "" {
		cfg.Terminal.IdleTimeout = "0" // 0 = never timeout; PTY lives until process exits or user closes
	}
	if cfg.Terminal.BufferLines <= 0 {
		cfg.Terminal.BufferLines = 2000
	}
	if cfg.Terminal.MaxLineBytes <= 0 {
		cfg.Terminal.MaxLineBytes = 65536 // 64KB per line
	}
	if cfg.Terminal.MaxBufferMB <= 0 {
		cfg.Terminal.MaxBufferMB = 4
	}
	if cfg.Terminal.MaxSessions <= 0 {
		cfg.Terminal.MaxSessions = 10
	}

	// --- DingTalk ---
	// Bool zero-value: enabled defaults to false (intentional — requires config), no presence check needed.

	// --- File Search ---
	if cfg.FileSearch.DisplayLimit <= 0 {
		cfg.FileSearch.DisplayLimit = 100
	}

	// --- PushMode ---
	if cfg.PushMode == "" {
		if cfg.DingTalk.Enabled {
			cfg.PushMode = "dingtalk"
		} else if cfg.Feishu.Enabled {
			cfg.PushMode = "feishu"
		} else {
			cfg.PushMode = "native"
		}
	}
	// Keep DingTalk.Enabled in sync with PushMode
	cfg.DingTalk.Enabled = cfg.PushMode == "dingtalk"
	// Keep Feishu.Enabled in sync with PushMode
	cfg.Feishu.Enabled = cfg.PushMode == "feishu"
	// WeChat is deliberately NOT part of the derivation above and has no
	// Enabled flag to sync. Its credentials only exist after a successful QR
	// scan, and the scan writes push_mode itself — so deriving "wechat" from a
	// leftover bot_token would silently re-enable a channel the user logged out
	// of (or whose token the server has since expired).

	// --- Forge (GitHub / GitLab integration) ---
	// The master switch defaults to ON: bool zero-value trap, same as terminal /
	// port_forward. An absent key means "keep the integration", so upgrading
	// never silently turns it off; an explicit `enabled: false` is respected.
	if !presence["forge.enabled"] {
		cfg.Forge.Enabled = true
	}
	// Notification toggles default to ENABLED. Go's bool zero value is false, so
	// without this block every flag would silently default to off — the opposite
	// of the documented behavior. Presence is used to distinguish "user wrote
	// false" from "user omitted the field": an absent key means default (true),
	// a present key means respect the parsed value.
	applyForgeNotifyDefaults(cfg, presence)
	normalizeForgeCredentialKeys(cfg)

	// --- Mail (built-in mail client) ---
	// The master switch defaults to ON for the same reason as forge.enabled: a
	// bool zero value would silently turn mail off for every install that has
	// never written the key. An explicit `enabled: false` is respected.
	if !presence["mail.enabled"] {
		cfg.Mail.Enabled = true
	}

	// --- Skills (cross-agent skill discovery) ---
	// Enabled defaults to false: auto-injecting every discovered skill spends
	// context on every turn whether or not the user wants it, so it is opt-in.
	// Use the presence map to distinguish "user wrote true" from "user omitted
	// the field" — a present key means respect the parsed value. Scanning and
	// the settings listing still work when off; the explicit "#skill" reference
	// is unaffected (it is a direct user instruction, not automatic injection).
	if p, ok := presence["skills.enabled"]; !ok || !p {
		cfg.Skills.Enabled = false
	}
	if len(cfg.Skills.Dirs) == 0 {
		// Migrate the pre-list key. `dir` was the single user skill directory
		// before `dirs` replaced it; a config written by an older build carries
		// only `dir`, and ignoring it would silently drop the user's configured
		// directory. Only used when the new key is absent — a config carrying
		// both has already been migrated (or hand-edited), and the new key wins.
		//
		// There is deliberately NO default directory: an empty list means the
		// user has no custom directories, and it must stay empty (a synthesized
		// default would reappear after the user removed the last entry).
		if cfg.Skills.LegacyDir != "" {
			cfg.Skills.Dirs = []string{cfg.Skills.LegacyDir}
		}
	}
	// The legacy key has served its purpose; clearing it keeps the next config
	// write from emitting both forms.
	cfg.Skills.LegacyDir = ""
	// RefreshHours: 0 = startup-only is a meaningful choice, so it cannot use a
	// `<= 0 → default` rewrite. Only an omitted field takes the 6h default;
	// negative values (hand-edited yaml) clamp to 0.
	if p, ok := presence["skills.refresh_hours"]; !ok || !p {
		cfg.Skills.RefreshHours = 6
	}
	if cfg.Skills.RefreshHours < 0 {
		cfg.Skills.RefreshHours = 0
	}
	// Fill in a slug for every repo so the checkout directory is stable even if
	// the user never opens the settings page.
	for i := range cfg.Skills.Repos {
		if cfg.Skills.Repos[i].Slug == "" {
			cfg.Skills.Repos[i].Slug = SkillSlug(cfg.Skills.Repos[i].URL)
		}
	}

	// --- Usage meter ---
	// Only normalize the shape of an ALREADY-CONFIGURED rule. There is
	// deliberately no default rule: an unconfigured install must stay silent
	// (a synthesized "30 days / $20" would fire a false alarm on every fresh
	// install, and the number would be wrong for essentially everyone).
	//
	// Every field is optional, so each one is normalized only when it can be
	// used: a quota without a period keeps PeriodDays at 0, which the service
	// reads as "no cycle" rather than silently inventing a 30-day rollover that
	// would reset the user's running total every month.
	if UsageMeterConfigured(cfg.UsageMeter) {
		// A rule configured before the enable flag existed must stay on. The
		// presence map is what distinguishes "the file has no such key" (an old
		// install → inherit from the rule) from "the user turned it off" (a
		// written false, which must be respected).
		if !presence["usage_meter.enabled"] {
			cfg.UsageMeter.Enabled = true
		}
		// Normalize the mode even when it is empty: "" means "fixed", and
		// writing that back keeps config.yaml readable and makes the value the
		// settings page shows identical to the one the arithmetic uses.
		cfg.UsageMeter.CycleMode = NormalizeUsageMeterCycleMode(cfg.UsageMeter.CycleMode)
		if cfg.UsageMeter.PeriodDays < 0 {
			cfg.UsageMeter.PeriodDays = 0
		}
		if cfg.UsageMeter.PeriodDays > MaxUsageMeterPeriodDays {
			cfg.UsageMeter.PeriodDays = MaxUsageMeterPeriodDays
		}
		if cfg.UsageMeter.Metric == "" {
			cfg.UsageMeter.Metric = UsageMeterMetricCost
		}
	}

	return autoPassword
}

// normalizeForgeCredentialKeys rewrites credential and scheme keys into the
// canonical host form.
//
// Older builds stored whatever the user typed after only lowercasing and
// trimming, so entering a URL — the very input this feature exists to support —
// persisted a row keyed "https://gitlab.internal". Lookups normalize their
// argument (ForgeToken calls NormalizeForgeHost), so such a row can never be
// found, and DELETE normalizes too, so it can never be removed either. The
// result is a credential the settings page reports as "Set" that no request can
// use and no click can clear.
//
// Normalizing here fixes every existing install in one place, on load, rather
// than leaving a permanent class of unreachable rows behind.
func normalizeForgeCredentialKeys(cfg *Config) {
	cfg.Forge.Credentials = normalizeForgeHostKeys(cfg.Forge.Credentials, "credential")
	cfg.Forge.Schemes = normalizeForgeHostKeys(cfg.Forge.Schemes, "scheme")
}

// normalizeForgeHostKeys rebuilds a host-keyed map with canonical keys,
// returning nil when there is nothing to do.
//
// On a collision the non-empty value wins: two spellings of one host must
// collapse to a single entry, and an empty value is the absence of information
// (an unset scheme), so it must not overwrite a real one. A collision between
// two *different* non-empty values keeps the first in sorted order, which makes
// the outcome deterministic rather than dependent on map iteration.
func normalizeForgeHostKeys(in map[string]string, label string) map[string]string {
	if len(in) == 0 {
		return in
	}
	out := make(map[string]string, len(in))
	changed := false

	// Sort the source keys so a collision resolves the same way on every load.
	keys := make([]string, 0, len(in))
	for k := range in {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	for _, k := range keys {
		v := in[k]
		canonical := NormalizeForgeHost(k)
		if canonical == "" {
			// Nothing usable to key on; dropping it is the only option that
			// does not leave an unreachable row behind.
			slog.Warn("dropping forge entry with unusable host", slog.String("kind", label), slog.String("host", k))
			changed = true
			continue
		}
		if canonical != k {
			changed = true
		}
		if existing, ok := out[canonical]; ok {
			changed = true
			if existing != "" {
				// Keep the existing value; the loser is recorded so a genuine
				// data conflict is visible rather than silently swallowed.
				slog.Warn("forge host collision, keeping first value",
					slog.String("kind", label), slog.String("host", canonical))
				continue
			}
		}
		out[canonical] = v
	}

	if !changed {
		return in
	}
	return out
}

// applyForgeNotifyDefaults fills the forge notification toggles, defaulting each
// absent flag to true. A flag explicitly present in the config file (even as
// false) is left untouched.
func applyForgeNotifyDefaults(cfg *Config, presence map[string]bool) {
	defaultTrue := func(key string, target *bool) {
		if _, present := presence[key]; !present {
			*target = true
		}
	}
	defaultTrue("forge.notify.opened", &cfg.Forge.Notify.Opened)
	defaultTrue("forge.notify.closed", &cfg.Forge.Notify.Closed)
	defaultTrue("forge.notify.merged", &cfg.Forge.Notify.Merged)
	defaultTrue("forge.notify.reopened", &cfg.Forge.Notify.Reopened)
	defaultTrue("forge.notify.commented", &cfg.Forge.Notify.Commented)
	defaultTrue("forge.notify.pipeline", &cfg.Forge.Notify.Pipeline)
}

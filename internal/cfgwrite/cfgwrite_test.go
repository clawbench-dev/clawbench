package cfgwrite

import (
	"os"
	"path/filepath"
	"runtime"
	"testing"

	"clawbench/internal/model"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
	"gopkg.in/yaml.v3"
)

// withDataDir points model.DataDir at a temp directory for the test.
func withDataDir(t *testing.T) string {
	t.Helper()
	orig := model.DataDir
	dir := t.TempDir()
	model.DataDir = dir
	t.Cleanup(func() { model.DataDir = orig })
	return dir
}

func readYAML(t *testing.T, dir string) map[string]any {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(dir, "config", "config.yaml"))
	require.NoError(t, err)
	var raw map[string]any
	require.NoError(t, yaml.Unmarshal(data, &raw))
	return raw
}

func TestPatch_CreatesFileAndMergesLeaves(t *testing.T) {
	dir := withDataDir(t)

	require.NoError(t, Patch(map[string]any{
		"mail": map[string]any{"enabled": true},
	}))
	raw := readYAML(t, dir)
	mail, ok := raw["mail"].(map[string]any)
	require.True(t, ok)
	assert.Equal(t, true, mail["enabled"])

	// A second patch touching a sibling field must keep the first one.
	require.NoError(t, Patch(map[string]any{
		"mail": map[string]any{"sync_window": 7},
	}))
	mail, _ = readYAML(t, dir)["mail"].(map[string]any)
	assert.Equal(t, true, mail["enabled"], "untouched fields must be preserved")
	assert.Equal(t, 7, mail["sync_window"])

	// A patch on a different section keeps both sections.
	require.NoError(t, Patch(map[string]any{"forge": map[string]any{"enabled": true}}))
	raw = readYAML(t, dir)
	assert.Contains(t, raw, "mail")
	assert.Contains(t, raw, "forge")
}

func TestPatch_WritesBackup(t *testing.T) {
	dir := withDataDir(t)

	require.NoError(t, Patch(map[string]any{"mail": map[string]any{"enabled": true}}))
	require.NoError(t, Patch(map[string]any{"mail": map[string]any{"enabled": false}}))

	_, err := os.Stat(filepath.Join(dir, "config", "config.yaml.bak"))
	require.NoError(t, err, "the previous file must be backed up before overwrite")

	// config.yaml holds secrets, so the backup must not be world-readable.
	// Windows does not carry Unix permission bits: Go reports 0666 for every
	// writable file there, so the mode assertion only means something elsewhere.
	info, err := os.Stat(filepath.Join(dir, "config", "config.yaml"))
	require.NoError(t, err)
	if runtime.GOOS != "windows" {
		assert.Equal(t, os.FileMode(0o600), info.Mode().Perm())
	}
}

func TestPatch_StripsAutoGeneratedPassword(t *testing.T) {
	dir := withDataDir(t)

	origAuto := model.PasswordIsAutoGenerated
	model.PasswordIsAutoGenerated = true
	t.Cleanup(func() { model.PasswordIsAutoGenerated = origAuto })

	require.NoError(t, Patch(map[string]any{"mail": map[string]any{"enabled": true}}))
	raw := readYAML(t, dir)
	assert.NotContains(t, raw, "password",
		"the auto-generated password is a runtime fallback, not configuration")

	// An explicit password patch must never be dropped.
	require.NoError(t, Patch(map[string]any{"password": "hash"}))
	raw = readYAML(t, dir)
	assert.Equal(t, "hash", raw["password"])
}

func TestPatch_DropsLegacyChatNickname(t *testing.T) {
	dir := withDataDir(t)

	require.NoError(t, Patch(map[string]any{"chat": map[string]any{"user_nickname": "alice"}}))
	raw := readYAML(t, dir)
	chat, _ := raw["chat"].(map[string]any)
	assert.NotContains(t, chat, "user_nickname", "the legacy key must not survive a write")
	// Whether the value migrates depends on whether user.nickname already exists
	// (the fresh-install branch dumps the whole ConfigInstance, which carries a
	// default). What must always hold is that the legacy key is gone.
	assert.NotContains(t, chat, "user_nickname")
}

func TestMergePatchIntoRaw(t *testing.T) {
	raw := map[string]any{
		"a": map[string]any{"x": 1, "y": 2},
		"b": "keep",
	}
	MergePatchIntoRaw(raw, map[string]any{
		"a": map[string]any{"y": 3, "z": 4},
		"c": 5,
	})

	a := raw["a"].(map[string]any)
	assert.Equal(t, 1, a["x"], "untouched nested leaves survive")
	assert.Equal(t, 3, a["y"], "touched nested leaves are replaced")
	assert.Equal(t, 4, a["z"], "new nested leaves are added")
	assert.Equal(t, "keep", raw["b"])
	assert.Equal(t, 5, raw["c"])

	// A leaf replaced by a map must not merge into the old scalar.
	raw2 := map[string]any{"k": "scalar"}
	MergePatchIntoRaw(raw2, map[string]any{"k": map[string]any{"n": 1}})
	assert.Equal(t, map[string]any{"n": 1}, raw2["k"])
}

func TestPatch_RecoversFromCorruptYAML(t *testing.T) {
	dir := withDataDir(t)
	require.NoError(t, os.MkdirAll(filepath.Join(dir, "config"), 0o755))
	require.NoError(t, os.WriteFile(
		filepath.Join(dir, "config", "config.yaml"),
		[]byte("not: [valid"), 0o600))

	require.NoError(t, Patch(map[string]any{"mail": map[string]any{"enabled": true}}))
	assert.Contains(t, readYAML(t, dir), "mail",
		"an unparseable file is replaced with a fresh map instead of failing the write")
}

func TestDropLegacyChatNickname_CreatesUserMap(t *testing.T) {
	raw := map[string]any{"chat": map[string]any{"user_nickname": "legacy"}}
	dropLegacyChatNickname(raw)

	user, ok := raw["user"].(map[string]any)
	require.True(t, ok, "a missing user section is created")
	assert.Equal(t, "legacy", user["nickname"])
	assert.NotContains(t, raw["chat"], "user_nickname")
}

func TestDropLegacyChatNickname_KeepsExistingNickname(t *testing.T) {
	raw := map[string]any{
		"chat": map[string]any{"user_nickname": "legacy"},
		"user": map[string]any{"nickname": "current"},
	}
	dropLegacyChatNickname(raw)

	user := raw["user"].(map[string]any)
	assert.Equal(t, "current", user["nickname"], "an existing nickname always wins")
	assert.NotContains(t, raw["chat"], "user_nickname")
}

// 第二次写入前必须先把现有文件备份成 .bak：配置里有 API key 与密码哈希，
// 一次写坏就没有回头路。
func TestPatch_BacksUpExistingConfig(t *testing.T) {
	dir := withDataDir(t)

	require.NoError(t, Patch(map[string]any{"chat": map[string]any{"page_size": 20}}))
	require.NoError(t, Patch(map[string]any{"chat": map[string]any{"page_size": 30}}))

	bak := filepath.Join(dir, "config", "config.yaml.bak")
	info, err := os.Stat(bak)
	require.NoError(t, err, "a second write must leave a backup")
	assert.Positive(t, info.Size())
}

// config 目录被一个同名文件占住时，MkdirAll 失败必须冒泡成 error——静默继续
// 会让调用方以为配置已经保存。
func TestPatch_FailsWhenConfigDirIsAFile(t *testing.T) {
	dir := withDataDir(t)
	require.NoError(t, os.WriteFile(filepath.Join(dir, "config"), []byte("x"), 0o644))

	assert.Error(t, Patch(map[string]any{"chat": map[string]any{"page_size": 1}}))
}

// 临时文件位置被目录占住时写入失败，错误必须冒泡（否则调用方以为保存成功）。
func TestPatch_FailsWhenTempPathIsADirectory(t *testing.T) {
	dir := withDataDir(t)
	require.NoError(t, os.MkdirAll(filepath.Join(dir, "config", "config.yaml.tmp"), 0o755))

	assert.Error(t, Patch(map[string]any{"chat": map[string]any{"page_size": 1}}))
}

// config.yaml 本身是个目录时，重命名必然失败；这条路径同时验证错误被包装
// 而不是 panic。
func TestPatch_FailsWhenConfigPathIsADirectory(t *testing.T) {
	dir := withDataDir(t)
	require.NoError(t, os.MkdirAll(filepath.Join(dir, "config", "config.yaml"), 0o755))

	assert.Error(t, Patch(map[string]any{"chat": map[string]any{"page_size": 1}}))
}
